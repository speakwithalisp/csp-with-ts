#!/usr/bin/env node
// Spec ledger: turns the test suite into a table the owner can review and sign off.
//
//   npm run specs                 run the tests, then write docs/tests/SPEC-LEDGER.md
//   npm run signoff -- C1 C2 ...  sign off the listed specs (as they are in the last run); "all" signs every spec
//   npm run signoff -- --list     show what needs review
//
// Sign-off stores a hash of each spec's ID, text and test body in docs/tests/signoff.json. If a test changes
// later, its hash changes and the ledger shows it as "needs re-review" until it is signed off again.
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, readdirSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { join } from 'node:path';

const root = process.cwd();
const metaDir = join(root, '.spec-meta');
const reportFile = join(metaDir, 'report.json');
const ledgerFile = join(root, 'docs', 'tests', 'SPEC-LEDGER.md');
const signoffFile = join(root, 'docs', 'tests', 'signoff.json');

const args = process.argv.slice(2);
const signoffMode = args[0] === '--signoff';

function runTests() {
    rmSync(metaDir, { recursive: true, force: true });
    mkdirSync(metaDir, { recursive: true });
    try {
        execFileSync('npx', ['vitest', 'run', '--reporter=default', '--reporter=json', `--outputFile.json=${reportFile}`], { stdio: 'inherit' });
    } catch {
        // failing tests still produce a report; the ledger shows them as FAILING
    }
}

function loadSpecs() {
    if (!existsSync(metaDir)) { return []; }
    return readdirSync(metaDir)
        .filter(f => f.endsWith('.json') && f !== 'report.json')
        .flatMap(f => JSON.parse(readFileSync(join(metaDir, f), 'utf8')));
}

function loadStatuses() {
    const statuses = new Map();
    if (!existsSync(reportFile)) { return statuses; }
    const report = JSON.parse(readFileSync(reportFile, 'utf8'));
    for (const file of report.testResults ?? []) {
        for (const t of file.assertionResults ?? []) {
            const m = /^\[([^\]]+)\]/.exec(t.title ?? '');
            if (m) { statuses.set(m[1], t.status); }
        }
    }
    return statuses;
}

const loadSignoff = () => (existsSync(signoffFile) ? JSON.parse(readFileSync(signoffFile, 'utf8')) : {});

function statusText(spec, status) {
    if (status === 'passed') { return spec.knownBug ? 'expected failure (known bug)' : 'passing'; }
    if (status === 'failed') { return spec.knownBug ? 'FIXED? (known-bug test now passes; flip it to a normal test)' : 'FAILING'; }
    return status ?? 'not run';
}

function signoffText(spec, signoff) {
    if (!(spec.id in signoff)) { return '☐ not signed'; }
    return signoff[spec.id] === spec.hash ? '✅ signed' : '⟳ needs re-review';
}

const esc = s => (s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');

function writeLedger(specs, statuses, signoff) {
    const byGroup = new Map();
    for (const s of specs.sort((a, b) => a.id.localeCompare(b.id, 'en', { numeric: true }))) {
        const group = s.kind === 'characterisation' ? 'Characterisation (behaviour to keep)' : `Specification: ${s.id.replace(/\d.*$/, '')}`;
        if (!byGroup.has(group)) { byGroup.set(group, []); }
        byGroup.get(group).push(s);
    }
    const counts = { total: specs.length, signed: 0, review: 0 };
    for (const s of specs) {
        const t = signoffText(s, signoff);
        if (t.startsWith('✅')) { counts.signed++; } else { counts.review++; }
    }
    let md = `# Spec ledger\n\nGenerated by \`npm run specs\` on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.\n\n`;
    md += `${counts.total} specs · ${counts.signed} signed off · ${counts.review} to review. `;
    md += 'Sign off with `npm run signoff -- <ID> [<ID> ...]` (or `all`).\n\n';
    md += 'Status: **passing**; **expected failure (known bug)**: written with `it.fails`, flips when the fix lands; **FAILING**: a real regression.\n\n';
    for (const [group, rows] of byGroup) {
        md += `## ${group}\n\n| ID | Must | Must not | Source | Status | Fixed by | Sign-off |\n|---|---|---|---|---|---|---|\n`;
        for (const s of rows) {
            md += `| ${s.id} | ${esc(s.must)} | ${esc(s.mustNot)} | ${esc(s.source)} | ${statusText(s, statuses.get(s.id))}${s.knownBug ? ` (${esc(s.knownBug)})` : ''} | ${esc(s.fixedBy)} | ${signoffText(s, signoff)} |\n`;
        }
        md += '\n';
    }
    md += '_Each row links to its test by ID: search the `test/` folder for `[ID]`._\n';
    mkdirSync(join(root, 'docs', 'tests'), { recursive: true });
    writeFileSync(ledgerFile, md);
    return counts;
}

if (signoffMode) {
    const specs = loadSpecs();
    if (!specs.length) { console.error('No spec metadata found. Run `npm run specs` first.'); process.exit(1); }
    const signoff = loadSignoff();
    const ids = args.slice(1);
    if (ids[0] === '--list' || !ids.length) {
        for (const s of specs) { const t = signoffText(s, signoff); if (!t.startsWith('✅')) { console.log(`${s.id}\t${t}\t${s.must}`); } }
        process.exit(0);
    }
    const wanted = ids[0] === 'all' ? specs.map(s => s.id) : ids;
    for (const id of wanted) {
        const s = specs.find(x => x.id === id);
        if (!s) { console.error(`Unknown spec ID: ${id}`); process.exitCode = 1; continue; }
        signoff[id] = s.hash;
    }
    writeFileSync(signoffFile, JSON.stringify(Object.fromEntries(Object.entries(signoff).sort()), null, 2) + '\n');
    writeLedger(specs, loadStatuses(), signoff);
    console.log(`Signed off: ${wanted.join(', ')}`);
} else {
    runTests();
    const counts = writeLedger(loadSpecs(), loadStatuses(), loadSignoff());
    console.log(`\nLedger written to docs/tests/SPEC-LEDGER.md: ${counts.total} specs, ${counts.signed} signed, ${counts.review} to review.`);
}
